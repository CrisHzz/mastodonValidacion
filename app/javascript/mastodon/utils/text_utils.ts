export const upper = (s: string) => s.toUpperCase();
export const lower = (s: string) => s.toLowerCase();
export const trim = (s: string) => s.trim();
export const len = (s: string) => s.length;
export const concat = (a: string, b: string) => a + b;
export const repeat = (s: string, n: number) => s.repeat(n);
export const split = (s: string, sep: string) => s.split(sep);
export const join = (arr: string[], sep: string) => arr.join(sep);
export const replace = (s: string, old: string, neu: string) => s.replace(old, neu);
export const includes = (s: string, sub: string) => s.includes(sub);

